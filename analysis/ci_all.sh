#!/bin/bash
# usage: analysis/ci_all.sh
#   Bootstrap 95% confidence intervals (analysis/bootstrap.py) for every geometric
#   mean reported in docs/paper-outline.md.  Reads results/ only; no measurement.
# output: results/analysis/ci_all.txt
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT/results"
BS="python3 -I $ROOT/analysis/bootstrap.py"
OUT=$ROOT/results/analysis/ci_all.txt
mkdir -p analysis

sec() { echo; echo "=== $*"; }
{
echo "# generated by analysis/ci_all.sh $(date -Is)"
for cpu in i5-1135g7 i9-14900k; do
  for o in O0 O1 O2 O3; do
    sec "micro $cpu -$o (cycles, vs cgoto_gcc)"; $BS ${cpu}_${o}_runs.csv
  done
done
for o in O2 O3; do
  sec "micro galaxy-s25edge -$o (cycles, vs cgoto_clang)"
  $BS --ref cgoto_clang-$o --only switch_clang-$o,musttail_clang-$o,mtargs_clang-$o micro_galaxy-s25edge_raw.txt
done

sec "Lua i9-14900k -O2, fixed seed (cycles, vs cgoto_gcc)"; $BS lua_i9-14900k_seedfix_raw.txt
sec "Lua i9-14900k -O2, clang only (vs cgoto_clang)"
$BS --ref cgoto_clang --only switch_clang,tail_clang,tailpn_clang lua_i9-14900k_seedfix_raw.txt
sec "Lua i9-14900k -O2, gcc only (vs cgoto_gcc)"
$BS --only switch_gcc,tail_gcc,tailpn_gcc lua_i9-14900k_seedfix_raw.txt
sec "Lua i9-14900k -O2, merge experiment (cycles, vs cgoto_gcc)"; $BS lua-merge_i9-14900k_raw.txt
for cc in gcc clang; do
  sec "Lua i9-14900k -O2, merge experiment, $cc (vs cgoto_$cc)"
  $BS --ref cgoto_$cc --only cgotonm_$cc,cgotobf_$cc,tailpn_$cc lua-merge_i9-14900k_raw.txt
  sec "Lua i9-14900k -O2, merge experiment, $cc (tailpn vs cgotonm)"
  $BS --ref cgotonm_$cc --only tailpn_$cc lua-merge_i9-14900k_raw.txt
done
sec "Lua i5-1135g7 -O2 (cycles, vs cgoto_gcc)"; $BS lua_i5-1135g7_raw.txt
sec "Lua i5-1135g7 -O2, merge experiment (cycles, vs cgoto_gcc)"; $BS lua-merge_i5-1135g7_raw.txt
for cc in gcc clang; do
  sec "Lua i5-1135g7 -O2, merge experiment, $cc (vs cgoto_$cc)"
  $BS --ref cgoto_$cc --only cgotonm_$cc,cgotobf_$cc,tailpn_$cc lua-merge_i5-1135g7_raw.txt
  sec "Lua i5-1135g7 -O2, merge experiment, $cc (tailpn vs cgotonm)"
  $BS --ref cgotonm_$cc --only tailpn_$cc lua-merge_i5-1135g7_raw.txt
done
sec "Lua i9-14900k -O3 (cycles, vs cgoto_gcc)"; $BS lua-O3_i9-14900k_raw.txt
sec "Lua i5-1135g7 -O3 (cycles, vs cgoto_gcc)"; $BS lua-O3_i5-1135g7_raw.txt
sec "Lua galaxy-s25edge -O2 (cycles, vs cgoto_clang)"; $BS --ref cgoto_clang lua_galaxy-s25edge_raw.txt

for f in wamr_i9-14900k wamr_i5-1135g7 wamr-O2_i9-14900k wamr-O2_i5-1135g7; do
  sec "WAMR $f (cycles, vs cgoto_gcc; switch uses another bytecode format)"; $BS ${f}_raw.txt
done

sec "CPython i9-14900k, no PGO (time, vs cgoto_gcc)"; $BS --metric time cpython_i9-14900k/*.json
sec "CPython i9-14900k, PGO+LTO (time, vs cgoto_gcc)"; $BS --metric time cpython-pgo_i9-14900k/*.json
sec "CPython i9-14900k, PGO+LTO, clang only (vs cgoto_clang)"
$BS --metric time --ref cgoto_clang --only switch_clang,tail_clang cpython-pgo_i9-14900k/*.json
} | tee "$OUT"
