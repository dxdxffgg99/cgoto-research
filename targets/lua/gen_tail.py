"""Generate a tail-call (musttail) dispatch version of Lua 5.4's luaV_execute.

usage: python3 -I gen_tail.py <orig lvm.c> <out dir>
writes <out dir>/lvm.c (original + #if switch) and <out dir>/lvm_tail.inc

Every opcode handler body is copied verbatim from the original switch;
only control transfer is rewritten:
  vmbreak;            -> DISPATCH();            (fetch next, musttail to its handler)
  goto startfunc;     -> TAIL(op_startfunc);
  goto ret;           -> TAIL(op_ret);
  goto l_tforcall;    -> TAIL(op_OP_TFORCALL);
  goto l_tforloop;    -> TAIL(op_OP_TFORLOOP);
State (L, ci, k, base, pc, i|trap<<32) travels in 6 register arguments.
"""
import re
import sys

src_path, out_dir = sys.argv[1], sys.argv[2]
lines = open(src_path).read().split("\n")

FUNC = "void luaV_execute (lua_State *L, CallInfo *ci) {"
f_start = lines.index(FUNC)
sw_start = next(n for n in range(f_start, len(lines))
                if lines[n].strip() == "vmdispatch (GET_OPCODE(i)) {")
# switch closes at the first line that is exactly 4 spaces + "}"
sw_end = next(n for n in range(sw_start + 1, len(lines)) if lines[n] == "    }")
# function closes at first "}" at column 0 after the switch
f_end = next(n for n in range(sw_end, len(lines)) if lines[n] == "}")

case_re = re.compile(r"^      vmcase\((OP_\w+)\) \{(\s*/\*.*\*/)?$")
cases = []  # (name, body lines)
cur = None
for ln in lines[sw_start + 1:sw_end]:
    m = case_re.match(ln)
    if m:
        cur = (m.group(1), [])
        cases.append(cur)
    else:
        assert cur is not None, ln
        cur[1].append(ln)

def transform(name, body):
    # drop the case's closing brace
    last = body[-1]
    assert last in ("      }", "      }}"), (name, last)
    body = body[:-1] + (["      }"] if last == "      }}" else [])
    out = []
    skip = False
    for ln in body:
        if name == "OP_RETURN1" and ln.strip().startswith("ret:"):
            out.append("        TAIL(op_ret);")
            skip = True
            continue
        if skip:
            continue
        ln = re.sub(r"^(\s*)l_tfor(call|loop): \{", r"\1{", ln)
        ln = ln.replace("vmbreak;", "DISPATCH();")
        ln = ln.replace("goto startfunc;", "TAIL(op_startfunc);")
        ln = ln.replace("goto ret;", "TAIL(op_ret);")
        ln = ln.replace("goto l_tforcall;", "TAIL(op_OP_TFORCALL);")
        ln = ln.replace("goto l_tforloop;", "TAIL(op_OP_TFORLOOP);")
        assert "goto" not in ln.split("/*")[0], (name, ln)
        out.append(ln)
    text = "\n".join(out)
    pre = ["  UNPACK();"]
    if re.search(r"\bcl\b", text):
        pre.append("  LClosure *cl = ci_func(ci);")
    return "\n".join([f"static void PN op_{name} (PARAMS) {{"] + pre + out + ["}"])

# opcode order from lopcodes.h enum
lop = open(src_path.replace("lvm.c", "lopcodes.h")).read()
enum = lop[lop.index("typedef enum {"):lop.index("} OpCode;")]
order = re.findall(r"^(OP_\w+)\s*(?:,|/\*)", enum, re.M)
names = [c[0] for c in cases]
assert sorted(order) == sorted(names), set(order) ^ set(names)

inc = []
inc.append("""/*
** Tail-call dispatch for luaV_execute. Generated by targets/lua/gen_tail.py
** from the original lvm.c switch; handler bodies are unchanged.
*/
#include <stdint.h>

#define MUSTTAIL __attribute__((musttail))
#if defined(LUA_TAIL_PRESERVE_NONE) && LUA_TAIL_PRESERVE_NONE
#define PN __attribute__((preserve_none))  /* handlers save no callee-saved regs */
#else
#define PN
#endif
#define PARAMS lua_State *L, CallInfo *ci, TValue *k, StkId base, \\
               const Instruction *pc, uint64_t ti
#define PACK(i,t)  ((uint64_t)(Instruction)(i) | ((uint64_t)(unsigned)(t) << 32))
#define UNPACK()   Instruction i = (Instruction)ti; int trap = (int)(ti >> 32); \\
                   (void)i; (void)trap
#define TAIL(f)    do { MUSTTAIL return f(L, ci, k, base, pc, PACK(i, trap)); } while (0)
#define DISPATCH() do { \\
    if (l_unlikely(trap)) {  /* stack reallocation or hooks? */ \\
      trap = luaG_traceexec(L, pc);  /* handle hooks */ \\
      updatebase(ci);  /* correct stack */ \\
    } \\
    i = *(pc++); \\
    MUSTTAIL return disptab_tail[GET_OPCODE(i)](L, ci, k, base, pc, PACK(i, trap)); \\
  } while (0)

typedef void (PN *luaV_op) (PARAMS);
static void PN op_startfunc (PARAMS);
static void PN op_returning (PARAMS);
static void PN op_ret (PARAMS);
""")
inc += [f"static void PN op_{n} (PARAMS);" for n in order]
inc.append("\nstatic const luaV_op disptab_tail[NUM_OPCODES] = {")
inc += [f"  op_{n}," for n in order]
inc.append("};\n")
inc.append("""static void PN op_startfunc (PARAMS) {
  UNPACK();
  trap = L->hookmask;
  TAIL(op_returning);
}

static void PN op_returning (PARAMS) {  /* trap already set */
  UNPACK();
  LClosure *cl = ci_func(ci);
  k = cl->p->k;
  pc = ci->u.l.savedpc;
  if (l_unlikely(trap))
    trap = luaG_tracecall(L);
  base = ci->func.p + 1;
  DISPATCH();
}

static void PN op_ret (PARAMS) {  /* return from a Lua function */
  UNPACK();
  if (ci->callstatus & CIST_FRESH)
    return;  /* end this frame */
  ci = ci->previous;
  TAIL(op_returning);  /* continue running caller in this frame */
}
""")
for name, body in cases:
    inc.append(transform(name, body) + "\n")
inc.append("""void luaV_execute (lua_State *L, CallInfo *ci) {
  op_startfunc(L, ci, NULL, NULL, NULL, 0);
}""")

open(f"{out_dir}/lvm_tail.inc", "w").write("\n".join(inc) + "\n")

patched = (lines[:f_start]
           + ["#if defined(LUA_USE_TAILCALL) && LUA_USE_TAILCALL",
              '#include "lvm_tail.inc"',
              "#else"]
           + lines[f_start:f_end + 1]
           + ["#endif"]
           + lines[f_end + 1:])
open(f"{out_dir}/lvm.c", "w").write("\n".join(patched))
print(f"{len(cases)} handlers -> {out_dir}/lvm_tail.inc")
